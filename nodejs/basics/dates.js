console.log("Month is : " + today.getMonth());
console.log("Day is : " + today.getDay());
console.log("Year is : " + today.getFullYear());
console.log("Hours is : " + today.getHours());
console.log("Minutes is : " + today.getMinutes());
console.log("Seconds is : " + today.getSeconds());
console.log("Milliseconds is : " + today.getMilliseconds());
