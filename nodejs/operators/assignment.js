// Assignment operators
/*
    equals = 
    plus equals +=
    minus equals -=
    product equals *=
    divide equals /=
    modulus equals %=
*/

let x = 10;
console.log(x);
console.log((x += 10));
x = 10;
console.log((x -= 10));
x = 10;
console.log((x *= 10));
x = 10;
console.log((x /= 10));
x = 10;
console.log((x %= 10));

