// declare variable for operations
let n = 10;
let m = 20;

// add
console.log(n + m);
// subtract
console.log(n - m);
//multiply
console.log(n * m);
//divide
console.log(n / m);
//mod
console.log(n % m);

// increment and decrement
// x++ or ++x same as x = x +1
// x-- or --x same as x = x-1

let x = 1;
console.log(x++); // 1
console.log(++x); // 3
console.log(x--); //3
console.log(--x); //1
