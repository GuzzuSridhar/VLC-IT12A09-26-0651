// comparision operators
// the result of a comparision operator is always true or false (boolean)

// equality check (==)
console.log(5 == 5);
console.log("5" == 5); // equality check with no type check
console.log("5" === 5); // equality check with type check

// non equality check (!=)
console.log(5 != 5);

// greater than (or equals)
console.log(5 > 5);
console.log(5 >= 5);
console.log(5 > 7);
console.log(5 >= 7);
console.log(15 >= 7);

//lesser than (or equals)
console.log(5 < 5);
console.log(5 <= 5);
console.log(5 < 7);
console.log(5 <= 7);
console.log(15 <= 7);
